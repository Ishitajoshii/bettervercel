export function createWorkflow(settings) {
  const workflow = `bettervercel-${settings.projectId}.yml`;
  const runner = `tooling/.github/bettervercel/${settings.projectId}.cjs`;
  const config = Buffer.from(JSON.stringify(settings)).toString('base64');
  return `# Generated by Better Vercel. Source is pinned to the reviewed commit.
name: Better Vercel ${settings.projectId}
on:
  push:
    paths: [".github/workflows/${workflow}"]
  workflow_dispatch:
permissions:
  contents: read
concurrency:
  group: bettervercel-${settings.projectId}
  cancel-in-progress: false
jobs:
  deploy:
    runs-on: ubuntu-latest
    timeout-minutes: 10
    env:
      BETTERVERCEL_IMPORT: ${config}
    steps:
      - uses: actions/checkout@v6
        with:
          path: tooling
          persist-credentials: false
          sparse-checkout: .github/bettervercel
      - uses: actions/checkout@v6
        with:
          path: source
          ref: "${settings.commitSha}"
          persist-credentials: false
      - uses: actions/setup-node@v6
        with:
          node-version: '24'
          package-manager-cache: false
      - name: Install and build
        run: node ${runner} build
      - name: Publish preview
        env:
          BETTERVERCEL_TOKEN: \${{ secrets.${settings.secretName} }}
        run: node ${runner} deploy
`;
}
